ACC = {'Á':'A','É':'E','Í':'I','Ó':'O','Ú':'U','À':'A','È':'E','Ò':'O'}
MISSING = set()   # characters used in hand() that have no glyph; check after rendering
SP = 1.5

def _glyph(ch):
    if ch in ACC:
        w, st = G[ACC[ch]]
        c = w / 2
        return w, st + [[(c - 0.4, -0.6), (c + 0.8, -1.8)]]
    if ch == 'Ü':
        w, st = G['U']
        return w, st + [[(1.2, -1.2), (1.2, -0.9)], [(2.8, -1.2), (2.8, -0.9)]]
    if ch not in G:
        MISSING.add(ch)
    return G.get(ch, G[' '])

def hand_width(s, cap):
    u = cap / 6
    s = s.upper()
    return sum(_glyph(c)[0] + SP for c in s) * u - SP * u

def hand(d, x, y, s, cap=12, anchor="l", width=None, color=INK):
    """y = vertical center of capitals"""
    s = s.upper()
    u = cap / 6
    tw = hand_width(s, cap)
    if anchor == "m": x -= tw / 2
    elif anchor == "r": x -= tw
    width = width or max(1.3, cap * 0.13)
    top = y - cap / 2
    cx = x
    for ch in s:
        w, strokes = _glyph(ch)
        dy = d.rnd.uniform(-0.3, 0.3) * u
        sk = d.rnd.uniform(-0.05, 0.05)
        for st in strokes:
            pts = []
            for px, py in st:
                pts.append((cx + (px + sk * (6 - py)) * u + d.rnd.uniform(-0.12, 0.12) * u,
                            top + dy + py * u + d.rnd.uniform(-0.12, 0.12) * u))
            if len(pts) == 2 and math.hypot(pts[1][0]-pts[0][0], pts[1][1]-pts[0][1]) < u * 0.6:
                r = width * 0.75
                d.d.ellipse([(pts[0][0]-r)*S, (pts[0][1]-r)*S, (pts[0][0]+r)*S, (pts[0][1]+r)*S], fill=color)
                continue
            pts = d._densify(pts, 2.5)
            d._poly(d._wobble(pts, 0.25), width, color)
        cx += (w + SP) * u
    return tw

def hatch(d, x, y, w, h, gap=5, width=1.2, color=INK):
    t = -h
    while t < w:
        u0, u1 = max(0, -t), min(h, w - t)
        if u1 > u0:
            d.line(x + t + u0, y + h - u0, x + t + u1, y + h - u1, width, color, overshoot=False)
        t += gap

def bar(d, x, y, w, h=12):
    d.rect(x, y, w, h, 2, 2.4)
    hatch(d, x + 1, y + 1, w - 2, h - 2, 4, 1.1)

def scribble(d, cx, cy, w, h):
    d.rect(cx - w/2, cy - h/2, w, h, 3, 3)
    t = -h
    while t < w + 4:
        d.line(cx - w/2 + t - 4, cy + h/2 + 6, cx - w/2 + t + h + 4, cy - h/2 - 6, 2.6, overshoot=False)
        t += 15
